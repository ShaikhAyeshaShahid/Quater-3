def main():
    anton = 18
    beth = anton * 2

    chen = beth - 5

    drew = anton + chen

    ethan = drew + 2

    print(f"Anton is {anton} years old.")
    print(f"Beth is {beth} years old.")
    print(f"Chen is {chen} years old.")
    print(f"Drew is {drew} years old.")
    print(f"Ethan is {ethan} years old.")

if __name__ == '__main__':
    main()
